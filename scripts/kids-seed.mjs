#!/usr/bin/env node
/**
 * Kids' category dictionaries (custom-category spec, Part B).
 *
 * Source of truth is one JSON file per category in db/seed/kids/. This script
 * checks them against the §B3 rules that a machine can check, and with
 * --write generates db/seed/kids.sql, which `npm run db:seed` applies.
 *
 *   node scripts/kids-seed.mjs            # check every category
 *   node scripts/kids-seed.mjs toy pet    # check some
 *   node scripts/kids-seed.mjs --write    # check all, then write kids.sql
 *
 * JSON shape:
 *   { "slug": "toy", "reviewed": "2026-10-13",
 *     "items": [{ "name": "Lego", "popular": true, "aliases": ["Legos"] }, ...] }
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RegExpMatcher, englishDataset, englishRecommendedTransformers } from 'obscenity';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'db', 'seed', 'kids');
const OUTPUT = join(ROOT, 'db', 'seed', 'kids.sql');

/** Size class per slug, and the active-item minimum (§7: 113 / 75 / 38). */
export const KIDS_CATEGORIES = {
  'cartoon-character': 'large',
  'kids-tv-show': 'large',
  'animated-movie': 'large',
  'video-game': 'large',
  toy: 'large',
  'dream-job': 'large',
  pokemon: 'large',
  candy: 'medium',
  'ice-cream-flavor': 'medium',
  'breakfast-cereal': 'medium',
  superhero: 'medium',
  dinosaur: 'medium',
  'book-series': 'medium',
  vehicle: 'medium',
  superpower: 'small',
  'mythical-creature': 'small',
  pet: 'small',
  'playground-game': 'small',
};
const MINIMUM = { large: 113, medium: 75, small: 38 };
const POPULAR = 20;

const matcher = new RegExpMatcher({ ...englishDataset.build(), ...englishRecommendedTransformers });

/** Mirrors lib/engine/text.ts dedupeKey, accent folding included (§B8.4). */
function dedupeKey(text) {
  return text
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/[‘’]/g, "'")
    .toLocaleUpperCase('en-US')
    .replace(/[^A-Z0-9]/g, '');
}

function check(slug) {
  const problems = [];
  let data;
  try {
    data = JSON.parse(readFileSync(join(SOURCE, `${slug}.json`), 'utf8'));
  } catch (error) {
    return { slug, problems: [`cannot read ${slug}.json: ${error.message}`] };
  }
  const size = KIDS_CATEGORIES[slug];
  if (data.slug !== slug) problems.push(`slug field is "${data.slug}"`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(data.reviewed ?? '')) problems.push('reviewed date missing (YYYY-MM-DD)');
  const items = Array.isArray(data.items) ? data.items : [];
  const keys = new Map();
  const claim = (text, owner) => {
    const key = dedupeKey(text);
    if (!key) return problems.push(`"${text}" has no letters or digits`);
    if (keys.has(key)) problems.push(`"${text}" duplicates "${keys.get(key)}"`);
    else keys.set(key, owner);
  };
  for (const item of items) {
    const name = item.name;
    if (typeof name !== 'string' || name.trim() !== name || name.length < 1) {
      problems.push(`bad name ${JSON.stringify(name)}`);
      continue;
    }
    if (name.length > 30) problems.push(`"${name}" is over 30 characters`);
    if (matcher.hasMatch(name)) problems.push(`"${name}" trips the profanity filter`);
    if (/\s{2,}/.test(name)) problems.push(`"${name}" has doubled spaces`);
    claim(name, name);
    for (const alias of item.aliases ?? []) {
      if (alias.length > 30) problems.push(`alias "${alias}" is over 30 characters`);
      if (matcher.hasMatch(alias)) problems.push(`alias "${alias}" trips the profanity filter`);
      claim(alias, name);
    }
  }
  const popular = items.filter((i) => i.popular).length;
  if (items.length < MINIMUM[size]) problems.push(`${items.length} items, ${size} needs ${MINIMUM[size]}`);
  if (popular !== POPULAR) problems.push(`${popular} popular items, need exactly ${POPULAR}`);
  return { slug, problems, items: items.length, popular, data };
}

const sqlText = (s) => `'${s.replaceAll("'", "''")}'`;

function toSql(results) {
  const out = [
    "-- Kids' category dictionaries (custom-category spec, Part B).",
    '-- GENERATED by scripts/kids-seed.mjs from db/seed/kids/*.json. Edit the JSON, not this file.',
    '-- Idempotent: every insert is "on conflict do nothing". Retirements live in retirements.sql.',
    '',
  ];
  for (const { slug, data, items, popular } of results) {
    out.push(`-- ${slug}: ${items} items, ${popular} popular, reviewed ${data.reviewed}`);
    out.push('insert into this_or_that.dictionary (category_id, canonical_name, popular_tier, player_originated)');
    out.push('select c.id, v.name, v.popular, false');
    out.push('from this_or_that.categories c');
    out.push('join (values');
    out.push(data.items.map((i) => `    (${sqlText(i.name)}, ${i.popular ? 'true' : 'false'})`).join(',\n'));
    out.push(`) as v(name, popular) on c.slug = ${sqlText(slug)}`);
    out.push('on conflict do nothing;');
    out.push('');
    const aliases = data.items.flatMap((i) => (i.aliases ?? []).map((a) => [a, i.name]));
    if (aliases.length) {
      out.push('insert into this_or_that.dictionary_aliases (dictionary_id, alias)');
      out.push('select d.id, v.alias');
      out.push('from (values');
      out.push(aliases.map(([a, n]) => `    (${sqlText(a)}, ${sqlText(n)})`).join(',\n'));
      out.push(') as v(alias, name)');
      out.push(`join this_or_that.categories c on c.slug = ${sqlText(slug)}`);
      out.push('join this_or_that.dictionary d on d.category_id = c.id and lower(d.canonical_name) = lower(v.name)');
      out.push('on conflict do nothing;');
      out.push('');
    }
  }
  return out.join('\n');
}

const args = process.argv.slice(2);
const write = args.includes('--write');
const wanted = args.filter((a) => !a.startsWith('--'));
const available = new Set(readdirSync(SOURCE).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)));
const slugs = wanted.length ? wanted : Object.keys(KIDS_CATEGORIES).filter((s) => write || available.has(s));

let failed = false;
const results = [];
for (const slug of slugs) {
  if (!(slug in KIDS_CATEGORIES)) {
    console.log(`✗ ${slug}: not a kids' category`);
    failed = true;
    continue;
  }
  const result = check(slug);
  results.push(result);
  if (result.problems.length) {
    failed = true;
    console.log(`✗ ${slug}`);
    for (const p of result.problems) console.log(`    ${p}`);
  } else {
    console.log(`✓ ${slug}: ${result.items} items, ${result.popular} popular`);
  }
}

if (failed) process.exit(1);
if (write) {
  writeFileSync(OUTPUT, toSql(results));
  console.log(`wrote ${OUTPUT}`);
}
